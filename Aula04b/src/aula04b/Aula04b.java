/**
 * Nesse Programa vamos estudar a estrutura de repetição while (enqunato)
 */
package aula04b;
import javax.swing.JOptionPane;

public class Aula04b {
    
    public static void main(String[] args) {
        int contador = 1;
        
        while (contador <=10) {
            System.out.println ("Contador: " + contador);
            contador++;
        }
    }
    
}
